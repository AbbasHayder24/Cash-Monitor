function getCategoryLabel(cat, lang) {
  if (!cat) return "";
  const text = lang === "ar" ? (cat.nameAr || cat.nameEn || cat.id) : (cat.nameEn || cat.nameAr || cat.id);
  return cat.icon ? `${cat.icon} ${text}` : text;
}

function applyLanguage(lang, customBrand) {
  const dict = I18N[lang] || I18N.ar;
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (dict[key]) el.textContent = dict[key];
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    const key = el.getAttribute("data-i18n-placeholder");
    if (dict[key]) el.placeholder = dict[key];
  });

  document.querySelectorAll("[data-i18n-title]").forEach((el) => {
    const key = el.getAttribute("data-i18n-title");
    if (dict[key]) el.title = dict[key];
  });

  if (customBrand) {
    const titleEl = document.getElementById("brandTitleText");
    const subEl = document.getElementById("brandSubtitleText");
    const emblemEl = document.getElementById("brandEmblemText");
    if (titleEl && customBrand.name) titleEl.textContent = customBrand.name;
    if (emblemEl && customBrand.emblem) emblemEl.textContent = customBrand.emblem;
    if (subEl) {
      subEl.textContent =
        lang === "ar"
          ? customBrand.subtitleAr || dict.appSubtitle
          : customBrand.subtitleEn || dict.appSubtitle;
    }
    document.title = `${customBrand.name || "FinFlow"} — ${lang === "ar" ? customBrand.subtitleAr || dict.appSubtitle : customBrand.subtitleEn || dict.appSubtitle}`;
  }

  const toggleLabel = document.getElementById("langToggleLabel");
  if (toggleLabel) {
    toggleLabel.textContent = lang === "ar" ? "English" : "عربي";
  }
}
